// Development-only MDI renderer. Home Assistant supplies ha-icon in production.
import * as mdi from '@mdi/js';
import { writeFile } from 'node:fs/promises';
const names = 'calendar-clock fire flash gauge hand-back-right help-circle-outline home-account home-thermometer information-outline leaf lightning-bolt link-variant lock-outline lock-open-variant-outline lock-question menu motion-sensor motion-sensor-off pipe-valve progress-clock radiator-off snowflake sofa sofa-outline thermometer thermometer-check thermometer-high transmission-tower trending-up tune-variant water-percent window-closed-variant window-open-variant'.split(' ');
const paths = Object.fromEntries(names.map(name => {
  const key = 'mdi' + name.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('');
  if (!mdi[key]) throw new Error(`Missing fixture icon: ${name}`);
  return ['mdi:' + name, mdi[key]];
}));
const source = `// Generated by scripts/build-fixture-icons.mjs. Development fixtures only.
// Icon paths: Material Design Icons / Pictogrammers, @mdi/js 7.4.47, Apache-2.0.
// See tests/fixtures/ICONS-LICENSE.txt and docs/source-provenance.md.
const paths = ${JSON.stringify(paths)};
export function defineIcons() {
  if(customElements.get('ha-icon'))return;
  customElements.define('ha-icon', class extends HTMLElement {
    static observedAttributes=['icon'];
    constructor(){super();this.attachShadow({mode:'open'});}
    connectedCallback(){this.render();}
    attributeChangedCallback(){this.render();}
    render(){
      const name=this.getAttribute('icon'),path=paths[name];
      this.dataset.fixtureIconKnown=String(Boolean(path));
      this.shadowRoot.innerHTML='<style>:host{display:inline-flex;align-items:center;justify-content:center;width:var(--mdc-icon-size,24px);height:var(--mdc-icon-size,24px);flex-shrink:0}svg{display:block;width:100%;height:100%;fill:currentColor}</style><svg viewBox="0 0 24 24" aria-hidden="true"><path></path></svg>';
      this.shadowRoot.querySelector('path').setAttribute('d',path||paths['mdi:help-circle-outline']);
    }
  });
}
defineIcons();
`;
await writeFile(new URL('../tests/fixtures/icons.js', import.meta.url), source);
